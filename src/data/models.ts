// ==================== FUNCTIONS ====================

export function getModelById(id: string): AIModel | undefined {
  return models.find((m) => m.id === id);
}

export function getModelsByCategory(category: ModelCategory): AIModel[] {
  return models.filter((m) => m.category === category);
}

export function getModelsByCompany(companySlug: string): AIModel[] {
  return models.filter((m) => m.companySlug === companySlug);
}

export function getCompanyBySlug(slug: string): Company | undefined {
  return companies.find((c) => c.slug === slug);
}

export function searchModels(query: string): AIModel[] {
  const lower = query.toLowerCase();
  return models.filter(
    (m) =>
      m.name.toLowerCase().includes(lower) ||
      m.company.toLowerCase().includes(lower) ||
      m.description.toLowerCase().includes(lower) ||
      m.id.toLowerCase().includes(lower)
  );
}

export function getOpenSourceModels(): AIModel[] {
  return models.filter((m) => m.openSource);
}

export function getReasoningModels(): AIModel[] {
  return models.filter((m) => m.reasoning);
}

export function getAgenticModels(): AIModel[] {
  return models.filter((m) => m.agentic);
}

